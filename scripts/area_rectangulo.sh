#!/bin/bash
# Crear un script que calcule el área de un rectángulo para datos pre fijados
# Definir las variables
echo "Ejemplo de cálculo del área de un rectángulo"
echo "--------------------------------------------------"
echo "Definición de variables numéricas"
# Definir las variables numéricas
base=10
echo "Definición de la variable base con el valor $base"
altura=12
echo "Definición de la variable altura con el valor $altura"
# Realizar el cálculo del área
area=$((base * altura))
# Mostrar el resultado
echo "El área del rectángulo con base $base y altura $altura es: $area"
echo "--------------------------------------------------"
echo "Fin del script"
echo "--------------------------------------------------"